"""Generate plugin/Source/param_tables.h: the name and value-text table of every patch and element parameter, from
docs/param_display.json (the original's own display texts, captured by tools/emu/sweep_display.py in the emulator).

The Schwung module and the plugin show and speak these texts in their patch and element editors.

Usage: python3 -I schwung/tools/gen_param_tables.py    (rewrites plugin/Source/param_tables.h)

Kinds (as in tools/emu/gen_param_text.py):
  enum     {from, text} thresholds (blank / emulator-error texts dropped: such values show the text below them)
  numeric  a number per value (1025 samples, v = i / 1024) shown with the unit
  text     a text per value (1025 samples)
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SRC = os.path.join(ROOT, 'docs', 'param_display.json')
OUT = os.path.join(ROOT, 'plugin', 'Source', 'param_tables.h')


def cstr(s):
    out = []
    for ch in s:
        o = ord(ch)
        if ch in '\\"':
            out.append('\\' + ch)
        elif 32 <= o < 127:
            out.append(ch)
        else:  # keep the source ASCII; the module treats texts as Latin-1 / UTF-8 bytes
            for b in ch.encode('utf-8'):
                out.append('\\%03o' % b)
    return '"' + ''.join(out) + '"'


def fnum(v):
    s = repr(float(v))
    if s in ('inf', '-inf', 'nan'):
        return '0.0f'
    return s + 'f'


def main():
    d = json.load(open(SRC, encoding='utf-8'))
    out = ['// Generated by schwung/tools/gen_param_tables.py from docs/param_display.json (the original\'s display',
           '// texts). Do not edit; run the script again instead.', '#pragma once', '', 'namespace hs2m::tables {', '',
           'enum Kind { kEnum, kNumeric, kText };',
           'struct Seg { float from; const char* text; };',
           '// One parameter: name (nullptr = unnamed in the original), kind, and its value texts.',
           'struct Param { int idx; const char* name; int kind; const Seg* segs; int numSegs; const float* nums; '
           'const char* const* texts; const char* unit; };', '']
    nums_pool, texts_pool = {}, {}
    decls = []

    def nums_ref(vals):
        key = tuple(vals)
        if key not in nums_pool:
            name = f'kN{len(nums_pool)}'
            nums_pool[key] = name
            decls.append(f'inline constexpr float {name}[1025] = {{{", ".join(fnum(v) for v in vals)}}};')
        return nums_pool[key]

    def texts_ref(vals):
        key = tuple(vals)
        if key not in texts_pool:
            name = f'kT{len(texts_pool)}'
            texts_pool[key] = name
            decls.append(f'inline constexpr const char* {name}[1025] = {{{", ".join(cstr(v) for v in vals)}}};')
        return texts_pool[key]

    seg_count = [0]

    def segs_ref(segs):
        name = f'kS{seg_count[0]}'
        seg_count[0] += 1
        body = ', '.join(f'{{{fnum(f)}, {cstr(t)}}}' for f, t in segs)
        decls.append(f'inline constexpr Seg {name}[] = {{{body}}};')
        return name

    groups = [('kPatch', d['patch']), ('kElemCommon', d['element']['common'])]
    for t in range(7):
        groups.append((f'kElemType{t}', d['element'].get(f'type{t}', {})))
    group_bodies = []
    for gname, src in groups:
        rows = []
        for key in sorted(src, key=lambda k: int(k, 16)):
            e = src[key]
            idx = int(key, 16)
            name = e.get('name')
            name_c = cstr(name.strip()) if isinstance(name, str) and name.strip() else 'nullptr'
            kind = e['kind']
            unit = cstr(e.get('unit', '') or '')
            if kind == 'enum':
                segs = [(f, t) for f, t in e['segments'] if t.strip() and t != '<emu error>']
                if not segs:
                    segs = [(0.0, '')]
                rows.append(f'{{{idx}, {name_c}, kEnum, {segs_ref(segs)}, {len(segs)}, nullptr, nullptr, {unit}}}')
            elif kind == 'numeric':
                rows.append(f'{{{idx}, {name_c}, kNumeric, nullptr, 0, {nums_ref(e["values"])}, nullptr, {unit}}}')
            else:
                vals = [v if v != '<emu error>' else '' for v in e['values']]
                rows.append(f'{{{idx}, {name_c}, kText, nullptr, 0, nullptr, {texts_ref(vals)}, {unit}}}')
        group_bodies.append((gname, rows))
    out.extend(decls)
    out.append('')
    for gname, rows in group_bodies:
        out.append(f'inline constexpr Param {gname}[] = {{')
        out.extend('    ' + r + ',' for r in rows)
        out.append('};')
        out.append(f'inline constexpr int {gname}Count = int(sizeof({gname}) / sizeof({gname}[0]));')
    out.append('')
    out.append('}  // namespace hs2m::tables')
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='ascii', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print(f'wrote {OUT}: {len(nums_pool)} numeric curves, {len(texts_pool)} text tables, {seg_count[0]} enums')


if __name__ == '__main__':
    main()
