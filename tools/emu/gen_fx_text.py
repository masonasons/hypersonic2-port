"""Generate plugin/Source/FxText.h: every effect's knob names and value texts, from docs/effect_display.json (the
original's own paramName / paramDisplay, captured by sweep_fx_display.py in the emulator).

Usage: python -I tools/emu/gen_fx_text.py    (rewrites plugin/Source/FxText.h)

Texts are the original's, trimmed, as UTF-8 (the DLL's are Windows-1252: degree and cent signs). A knob whose display
follows a switch knob (Delay follows Sync: seconds when off, note values when on) gets one table per switch text.
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SRC = os.path.join(ROOT, 'docs', 'effect_display.json')
OUT = os.path.join(ROOT, 'plugin', 'Source', 'FxText.h')


def cstr(s):
    out = []
    for b in s.encode('utf-8'):
        c = chr(b)
        if c in '\\"':
            out.append('\\' + c)
        elif 32 <= b < 127:
            out.append(c)
        else:
            out.append('\\%03o' % b)  # octal: at most 3 digits, so a following digit is never taken into it
    return '"' + ''.join(out) + '"'


def clean_name(n):
    return n.strip().replace('<>', '/')  # "Cho<>Rev" reads as "Cho/Rev", not "less than greater than"


def main():
    d = json.load(open(SRC, encoding='utf-8'))
    out = ['// Generated by tools/emu/gen_fx_text.py from docs/effect_display.json (the original\'s effect knob names',
           '// and value texts). Do not edit; run the script again instead.', '#pragma once', '',
           'namespace hs2port::fxtext {', '',
           '// The text for samples from .. (next from) - 1, where sample = round(value * 1024).',
           'struct Seg { short from; const char* text; };',
           '// caseOn >= 0: the knob reads as cases[c] while knob caseOn is in its c-th text (from caseFrom[c]).',
           'struct Knob { const char* name; const Seg* segs; int numSegs; int caseOn; const Knob* cases; '
           'const short* caseFrom; int numCases; };',
           'struct Effect { int type; const Knob* knobs; int numKnobs; };  // knobs[i].name == nullptr: unused', '']

    def seg_array(name, segs):
        body = ', '.join(f'{{{k}, {cstr(t.strip())}}}' for k, t in segs)
        out.append(f'inline constexpr Seg {name}[] = {{{body}}};')

    effects = []
    for key in sorted((k for k in d if k != 'emu_errors'), key=int):
        e = d[key]
        t = int(key)
        knob_inits = []
        for i, k in enumerate(e['knobs']):
            if k is None:
                knob_inits.append('{nullptr, nullptr, 0, -1, nullptr, nullptr, 0}')
                continue
            base = f'kFx{t}K{i}'
            seg_array(base + 'Segs', k['segments'])
            cases = 'nullptr'
            case_from = 'nullptr'
            on, nc = -1, 0
            if 'cases' in k:
                c = k['cases']
                on, nc = c['on'], len(c['segments'])
                inits = []
                for ci, (_, ce) in enumerate(c['segments']):
                    seg_array(f'{base}C{ci}Segs', ce['segments'])
                    inits.append(f'{{{cstr(clean_name(k["name"]))}, {base}C{ci}Segs, {len(ce["segments"])}, '
                                 f'-1, nullptr, nullptr, 0}}')
                out.append(f'inline constexpr Knob {base}Cases[] = {{{", ".join(inits)}}};')
                out.append(f'inline constexpr short {base}CaseFrom[] = '
                           f'{{{", ".join(str(a) for a, _ in c["segments"])}}};')
                cases, case_from = base + 'Cases', base + 'CaseFrom'
            knob_inits.append(f'{{{cstr(clean_name(k["name"]))}, {base}Segs, {len(k["segments"])}, {on}, {cases}, '
                              f'{case_from}, {nc}}}')
        out.append(f'inline constexpr Knob kFx{t}Knobs[] = {{{", ".join(knob_inits)}}};  // {e["name"]}')
        out.append('')
        effects.append((t, len(knob_inits)))
    out.append('inline constexpr Effect kEffects[] = {' +
               ', '.join(f'{{{t}, kFx{t}Knobs, {n}}}' for t, n in effects) + '};')
    out += ['',
            'inline const Effect* findEffect(int type) {',
            '    for (const auto& e : kEffects)',
            '        if (e.type == type) return &e;',
            '    return nullptr;',
            '}',
            '',
            '}  // namespace hs2port::fxtext', '']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out))
    print(OUT, len(effects), 'effects')


if __name__ == '__main__':
    main()
