"""Generate plugin/Source/ParamText.h: value-text tables for the host parameters beyond the mixer (part settings,
arpeggiator, microtuning, global send FX), from docs/param_display.json (the original's own display texts, captured by
sweep_display.py in the emulator).

Usage: python -I tools/emu/gen_param_text.py    (rewrites plugin/Source/ParamText.h)

Kinds:
  enum     the display changes at fixed thresholds: {from, text} pairs (texts that are blank in the original, i.e.
           unused values, are dropped; such values show the text below them)
  numeric  a number per value (1025 samples, v = i / 1024); the plugin formats it with the unit given here
  text     a text per value (1025 samples), e.g. "-oo", "+12.0 dB"
"""
import json
import os

ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
SRC = os.path.join(ROOT, 'docs', 'param_display.json')
OUT = os.path.join(ROOT, 'plugin', 'Source', 'ParamText.h')

# (table name, section, key, unit for numeric kinds)
TABLES = [
    ('kOutput', 'patch', '0x3d', ''), ('kKeyLow', 'patch', '0x31', ''), ('kKeyHigh', 'patch', '0x32', ''),
    ('kKeyXfade', 'patch', '0x33', ''), ('kVelLow', 'patch', '0x34', ''), ('kVelHigh', 'patch', '0x35', ''),
    ('kVelXfade', 'patch', '0x36', ''), ('kTranspose', 'patch', '0x37', ''), ('kFineTune', 'patch', '0x38', 'cents'),
    ('kMaxVoices', 'patch', '0x3a', ''), ('kFxSends', 'patch', '0x3e', ''), ('kPbUp', 'patch', '0x49', ''),
    ('kPbDown', 'patch', '0x4a', ''), ('kMonoPoly', 'patch', '0x39', ''), ('kGlide', 'patch', '0x03', ''),
    ('kGlideTime', 'patch', '0x94', ''), ('kTuneRoot', 'patch', '0x4e', ''), ('kTuneDepth', 'patch', '0x53', '%'),
    ('kArpOn', 'patch', '0x11', ''), ('kArpLatch', 'patch', '0x12', ''), ('kArpMode', 'patch', '0x13', ''),
    ('kArpOctaves', 'patch', '0x14', ''), ('kArpSteps', 'patch', '0x15', ''), ('kArpSync', 'patch', '0x16', ''),
    ('kArpRate', 'patch', '0x17', ''), ('kArpGate', 'patch', '0x18', ''), ('kArpSwing', 'patch', '0x19', '%'),
    ('kFxMute', 'common', '0x00', ''), ('kFxLevel', 'common', '0x8b', ''), ('kFxPan', 'common', '0x8c', ''),
    ('kFxAux', 'type0', '0x14', ''), ('kFxSend', 'type0', '0x15', ''),
]


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    d = json.load(open(SRC, encoding='utf-8'))
    out = ['// Generated by tools/emu/gen_param_text.py from docs/param_display.json (the original\'s display texts).',
           '// Do not edit; run the script again instead.', '#pragma once', '', 'namespace hs2port::paramtext {', '',
           'struct Seg { float from; const char* text; };',
           'struct Table { int kind; const Seg* segs; int numSegs; const float* nums; const char* const* texts; '
           'const char* unit; };',
           'enum Kind { kEnum, kNumeric, kText };', '']
    text_arrays = {}  # dedupe identical text tables
    for name, section, key, unit in TABLES:
        src = d['patch'] if section == 'patch' else d['element'][section]
        e = src[key]
        kind = e['kind']
        if kind == 'enum':
            segs = [(f, t) for f, t in e['segments'] if t.strip() and t != '<emu error>']
            body = ', '.join(f'{{{f!r}f, {cstr(t)}}}' for f, t in segs)
            out.append(f'inline constexpr Seg {name}Segs[] = {{{body}}};')
            out.append(f'inline constexpr Table {name} = {{kEnum, {name}Segs, {len(segs)}, nullptr, nullptr, "{unit}"}};')
        elif kind == 'numeric':
            vals = ', '.join(f'{v!r}f' for v in e['values'])
            out.append(f'inline constexpr float {name}Nums[] = {{{vals}}};')
            out.append(f'inline constexpr Table {name} = {{kNumeric, nullptr, 0, {name}Nums, nullptr, "{unit}"}};')
        else:
            vals = tuple(e['values'])
            if vals not in text_arrays:
                text_arrays[vals] = f'{name}Texts'
                body = ', '.join(cstr(t) for t in vals)
                out.append(f'inline constexpr const char* {name}Texts[] = {{{body}}};')
            out.append(f'inline constexpr Table {name} = {{kText, nullptr, 0, nullptr, {text_arrays[vals]}, "{unit}"}};')
        out.append('')
    out.append('}  // namespace hs2port::paramtext')
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(out) + '\n')
    print(f'wrote {OUT}: {len(TABLES)} tables')


if __name__ == '__main__':
    main()
