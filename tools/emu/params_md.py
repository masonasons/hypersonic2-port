"""Render docs/param_display.json (from sweep_display.py) as a readable docs/PARAMS.md."""
import json
import os
import sys

TYPE_NAMES = ['Effect', 'Drawbar', 'Sample', 'Wavetable', 'FM', 'Analog', 'Model']


def describe(e):
    if e['kind'] == 'numeric':
        v, u = e['values'], e['unit']
        mid = v[len(v) // 2]
        return f"{v[0]:g} → {mid:g} (0.5) → {v[-1]:g} {u}".strip()
    if e['kind'] == 'enum':
        segs = [t.strip() for _, t in e['segments'] if t.strip() and t != '<emu error>']
        if any(s == '<emu error>' for _, s in e['segments']):
            return '*content lookup (name from bank)*'
        if len(segs) > 14:
            return f"{len(segs)} steps: {', '.join(segs[:5])} … {', '.join(segs[-3:])}"
        return ', '.join(segs)
    vals = [t for t in e['values'] if t.strip()]
    if any(t == '<emu error>' for t in e['values']):
        return '*content lookup / needs runtime state*'
    return f"text: {vals[0]!r} … {vals[len(vals) // 2]!r} … {vals[-1]!r}" if vals else ''


def table(title, entries, out):
    out.append(f'\n### {title}\n\n| idx | name | values |\n|---|---|---|')
    for k in sorted(entries, key=lambda x: int(x, 16)):
        e = entries[k]
        d = describe(e).replace('|', '\\|')
        out.append(f"| {k} | {e.get('name') or ''} | {d} |")


def main():
    docs = sys.argv[1]
    d = json.load(open(os.path.join(docs, 'param_display.json')))
    out = ['# Hypersonic 2 parameters',
           '',
           'Generated by `tools/emu/params_md.py` from `param_display.json`. Every value comes from running Hypersonic\'s own',
           'display code in an emulator (`tools/emu/sweep_display.py`). Stored values are floats 0..1.',
           '',
           '**Quantization:** every enum conversion is `trunc(v * K)` (the compiler\'s float→int sets the FPU to chop).',
           'Factory data stores bin centres `(n + 0.5) / K`. K is usually 1.9, 2.9, 3.9, 15.9, 71.9 or 128.9.',
           '',
           '**Numeric rows:** value at v=0 → v=0.5 → v=1, as displayed. Full 1025-point curves are in `param_display.json`.',
           '',
           '## Patch level']
    table('Patch parameters', d['patch'], out)
    out.append('\n## Element level')
    table('Common to all element types (as shown for type 2, Sample)', d['element']['common'], out)
    for t in range(7):
        k = f'type{t}'
        if k in d['element']:
            table(f'Type {t}: {TYPE_NAMES[t]} (type-specific rows, plus common rows that display differently)',
                  d['element'][k], out)
    open(os.path.join(docs, 'PARAMS.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    print(len(out), 'lines')


if __name__ == '__main__':
    main()
